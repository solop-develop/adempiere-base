CREATE OR REPLACE VIEW RV_KPI_RequestFollowUp
(RV_KPI_RequestFollowUp_ID,
 R_Request_ID, AD_Client_ID, AD_Org_ID, IsActive, Created, Updated, DocumentNo, R_RequestType_ID, R_Group_ID,
 R_Category_ID, R_Status_ID, R_Resolution_ID, R_RequestRelated_ID, Priority, PriorityUser, DueType, ConfidentialType,
 IsEscalated, IsSelfService, SalesRep_ID, AD_Role_ID, DateLastAction, DateLastAlert, LastResult, Processed,
 IsInvoiced, C_BPartner_ID, AD_User_ID, C_Campaign_ID, C_Order_ID, C_Invoice_ID, C_Payment_ID, M_Product_ID,
 C_Project_ID, A_Asset_ID, M_InOut_ID, M_RMA_ID, AD_Table_ID, RequestAmt, R_MailText_ID, Result,
 ConfidentialTypeEntry, R_StandardResponse_ID, NextAction, DateNextAction, StartTime, EndTime, QtySpent, QtyInvoiced,
 M_ProductSpent_ID, C_Activity_ID, StartDate, CloseDate, C_InvoiceRequest_ID, M_ChangeRequest_ID, TaskStatus,
 QtyPlan, DateCompletePlan, DateStartPlan, M_FixChangeNotice_ID, C_ProjectPhase_ID, C_ProjectTask_ID, User1_ID,
 User2_ID, User3_ID, User4_ID, C_OrderLine_ID, C_InvoiceLine_ID, DD_Order_ID, DD_OrderLine_ID, PP_Order_ID,
 PP_Cost_Collector_ID, M_Requisition_ID, M_RequisitionLine_ID, AD_OrgTrx_ID, M_InOutLine_ID, M_RMALine_ID, Subject,
 S_Contract_ID, S_ContractLine_ID, C_ProjectLine_ID, M_ChangeNotice_ID, RequestInfoType, M_Package_ID,
 M_Warehouse_ID, R_Milestone_ID, R_Release_ID, DurationEstimated, URL, R_Iteration_ID, TimeSpent, Labels,
 Discord_Thread_ID, IssueID, Discord_URL, IssueURL, DateInternalDelivery, Responsible_ID, Value, DateInternalReject,
 QtyInternalDelivery, QtyInternalReject,
 StatusIsClosed, StatusIsFinalClose, IsOpenRequest, NumRequests, AgeDays, ResolutionDays, IsOverdue, DaysOverdue,
 IsFollowUpDue, HasProject, HoursVariance)
AS
SELECT x.R_Request_ID,
    x.R_Request_ID, x.AD_Client_ID, x.AD_Org_ID, x.IsActive, x.Created, x.Updated, x.DocumentNo, x.R_RequestType_ID,
    x.R_Group_ID, x.R_Category_ID, x.R_Status_ID, x.R_Resolution_ID, x.R_RequestRelated_ID, x.Priority,
    x.PriorityUser, x.DueType, x.ConfidentialType, x.IsEscalated, x.IsSelfService, x.SalesRep_ID, x.AD_Role_ID,
    x.DateLastAction, x.DateLastAlert, x.LastResult, x.Processed, x.IsInvoiced, x.C_BPartner_ID, x.AD_User_ID,
    x.C_Campaign_ID, x.C_Order_ID, x.C_Invoice_ID, x.C_Payment_ID, x.M_Product_ID, x.C_Project_ID, x.A_Asset_ID,
    x.M_InOut_ID, x.M_RMA_ID, x.AD_Table_ID, x.RequestAmt, x.R_MailText_ID, x.Result, x.ConfidentialTypeEntry,
    x.R_StandardResponse_ID, x.NextAction, x.DateNextAction, x.StartTime, x.EndTime, x.QtySpent, x.QtyInvoiced,
    x.M_ProductSpent_ID, x.C_Activity_ID, x.StartDate, x.CloseDate, x.C_InvoiceRequest_ID, x.M_ChangeRequest_ID,
    x.TaskStatus, x.QtyPlan, x.DateCompletePlan, x.DateStartPlan, x.M_FixChangeNotice_ID, x.C_ProjectPhase_ID,
    x.C_ProjectTask_ID, x.User1_ID, x.User2_ID, x.User3_ID, x.User4_ID, x.C_OrderLine_ID, x.C_InvoiceLine_ID,
    x.DD_Order_ID, x.DD_OrderLine_ID, x.PP_Order_ID, x.PP_Cost_Collector_ID, x.M_Requisition_ID,
    x.M_RequisitionLine_ID, x.AD_OrgTrx_ID, x.M_InOutLine_ID, x.M_RMALine_ID, x.Subject, x.S_Contract_ID,
    x.S_ContractLine_ID, x.C_ProjectLine_ID, x.M_ChangeNotice_ID, x.RequestInfoType, x.M_Package_ID,
    x.M_Warehouse_ID, x.R_Milestone_ID, x.R_Release_ID, x.DurationEstimated, x.URL, x.R_Iteration_ID, x.TimeSpent,
    x.Labels, x.Discord_Thread_ID, x.IssueID, x.Discord_URL, x.IssueURL, x.DateInternalDelivery, x.Responsible_ID,
    x.Value, x.DateInternalReject, x.QtyInternalDelivery, x.QtyInternalReject,
    x.StatusIsClosed,
    x.StatusIsFinalClose,
    CAST((CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) AS INTEGER),
    CAST(1 AS INTEGER),
    CASE WHEN (CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) = 1 THEN CURRENT_DATE - CAST(x.Created AS DATE) ELSE NULL END,
    CASE WHEN (CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) = 0 AND x.CloseDate IS NOT NULL THEN CAST(x.CloseDate AS DATE) - CAST(x.Created AS DATE) ELSE NULL END,
    CAST((CASE WHEN (CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) = 1 AND x.DateCompletePlan IS NOT NULL AND CAST(x.DateCompletePlan AS DATE) < CURRENT_DATE THEN 1 ELSE 0 END) AS INTEGER),
    CASE WHEN (CASE WHEN (CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) = 1 AND x.DateCompletePlan IS NOT NULL AND CAST(x.DateCompletePlan AS DATE) < CURRENT_DATE THEN 1 ELSE 0 END) = 1 THEN CURRENT_DATE - CAST(x.DateCompletePlan AS DATE) ELSE 0 END,
    CAST(CASE WHEN (CASE WHEN x.IsActive = 'Y' AND COALESCE(x.StatusIsClosed, 'N') = 'N' THEN 1 ELSE 0 END) = 1 AND x.DateNextAction IS NOT NULL AND CAST(x.DateNextAction AS DATE) < CURRENT_DATE THEN 1 ELSE 0 END AS INTEGER),
    CASE WHEN x.C_Project_ID IS NOT NULL THEN 1 ELSE 0 END,
    CASE WHEN x.TimeSpent IS NOT NULL AND x.QtyPlan IS NOT NULL THEN x.TimeSpent - x.QtyPlan ELSE NULL END
FROM (
    SELECT r.R_Request_ID,
        r.AD_Client_ID, r.AD_Org_ID, r.IsActive, r.Created, r.Updated, r.DocumentNo, r.R_RequestType_ID,
        r.R_Group_ID, r.R_Category_ID, r.R_Status_ID, r.R_Resolution_ID, r.R_RequestRelated_ID, r.Priority,
        r.PriorityUser, r.DueType, r.ConfidentialType, r.IsEscalated, r.IsSelfService, r.SalesRep_ID, r.AD_Role_ID,
        r.DateLastAction, r.DateLastAlert, r.LastResult, r.Processed, r.IsInvoiced, r.C_BPartner_ID, r.AD_User_ID,
        r.C_Campaign_ID, r.C_Order_ID, r.C_Invoice_ID, r.C_Payment_ID, r.M_Product_ID, r.C_Project_ID, r.A_Asset_ID,
        r.M_InOut_ID, r.M_RMA_ID, r.AD_Table_ID, r.RequestAmt, r.R_MailText_ID, r.Result, r.ConfidentialTypeEntry,
        r.R_StandardResponse_ID, r.NextAction, r.DateNextAction, r.StartTime, r.EndTime, r.QtySpent, r.QtyInvoiced,
        r.M_ProductSpent_ID, r.C_Activity_ID, r.StartDate, r.CloseDate, r.C_InvoiceRequest_ID, r.M_ChangeRequest_ID,
        r.TaskStatus, r.QtyPlan, r.DateCompletePlan, r.DateStartPlan, r.M_FixChangeNotice_ID, r.C_ProjectPhase_ID,
        r.C_ProjectTask_ID, r.User1_ID, r.User2_ID, r.User3_ID, r.User4_ID, r.C_OrderLine_ID, r.C_InvoiceLine_ID,
        r.DD_Order_ID, r.DD_OrderLine_ID, r.PP_Order_ID, r.PP_Cost_Collector_ID, r.M_Requisition_ID,
        r.M_RequisitionLine_ID, r.AD_OrgTrx_ID, r.M_InOutLine_ID, r.M_RMALine_ID, r.Subject, r.S_Contract_ID,
        r.S_ContractLine_ID, r.C_ProjectLine_ID, r.M_ChangeNotice_ID, r.RequestInfoType, r.M_Package_ID,
        r.M_Warehouse_ID, r.R_Milestone_ID, r.R_Release_ID, r.DurationEstimated, r.URL, r.R_Iteration_ID,
        r.TimeSpent, r.Labels, r.Discord_Thread_ID, r.IssueID, r.Discord_URL, r.IssueURL, r.DateInternalDelivery,
        r.Responsible_ID, r.Value, r.DateInternalReject, r.QtyInternalDelivery, r.QtyInternalReject,
        rs.IsClosed AS StatusIsClosed, rs.IsFinalClose AS StatusIsFinalClose
    FROM R_Request r
        LEFT JOIN R_Status rs ON (rs.R_Status_ID = r.R_Status_ID)
) x;
