CREATE OR REPLACE VIEW RV_KPI_ProjectLine
(RV_KPI_ProjectLine_ID,
 C_ProjectLine_ID, AD_Client_ID, AD_Org_ID, IsActive, Created, Updated, C_Project_ID, Line, Description, PlannedQty,
 PlannedPrice, PlannedAmt, PlannedMarginAmt, CommittedAmt, M_Product_ID, M_Product_Category_ID, InvoicedAmt,
 InvoicedQty, CommittedQty, C_ProjectIssue_ID, C_Order_ID, C_OrderPO_ID, IsPrinted, Processed, C_ProjectPhase_ID,
 C_ProjectTask_ID, S_ResourceAssignment_ID, Vendor_ID, PP_Product_BOM_ID, AD_Workflow_ID, PP_Order_ID, C_RfQLine_ID,
 C_UOM_ID, DatePromised, EndDate, M_ProductionBatch_ID, QtyEntered, DurationUnit, DurationEstimated,
 C_ProjectLineType_ID, C_ProjectStatus_ID, C_ProjectTaskCategory_ID, C_StandardProjectLine_ID, DateDeadline,
 DateFinishSchedule, DateLastRun, DateNextRun, DateStartSchedule, DurationReal, Frequency, FrequencyType, Help,
 IsComplete, IsIndefinite, IsMilestone, IsRecurrent, IsSummary, Name, Parent_ID, PercentageCompleted, PriorityRule,
 ProjInvoiceRule, Responsible_ID, RunsMax, RunsRemaining, StartDate, ProjectLineType, IsDropShip,
 DropShip_BPartner_ID, DropShip_Location_ID, PriceEntered, SP027_Brand_ID, SP027_Period_ID, SP027_PBudgetLine_ID,
 SP027_BrandProduct_ID, SP027_PlannedAmt, IsCostBased, Margin, Cost, S_ResourceType_ID, Ref_BPartner_ID,
 IsCustomerApproved, CostPlannedAmt, CostOrderedAmt, CostInvoicedAmt, CostReceivedAmt, CostConsumedAmt, QtyOrdered,
 QtyDelivered, CostOrderedQty, CostReceivedQty, CostConsumedQty, CostInvoicedQty, OrderedAmt, DeliveredAmt,
 ProfitPlannedAmt, ProfitRealizedAmt, SP027_AdvertisingRule_ID, SP027_ResourceQuantity,
 ProjectValue, ProjectName, ProjectStatus_ID, ProjectIsOpen, ProjectManager_ID, C_BPartner_ID, C_ProjectType_ID,
 ProjectDeadline, LineKind, IsPhaseLine, IsMilestoneLine, IsResourceLine, IsDetailLine, LineCount, IsDone, IsOverdue,
 DaysOverdue, DaysToDeadline, HasOwner, HasDeadline, DurationVariance, ToInvoiceAmt, CommittedPct, InvoicedPct,
 MarginPlannedPct, ParentLineKind, ParentName)
AS
SELECT x.C_ProjectLine_ID,
    x.C_ProjectLine_ID, x.AD_Client_ID, x.AD_Org_ID, x.IsActive, x.Created, x.Updated, x.C_Project_ID, x.Line,
    x.Description, x.PlannedQty, x.PlannedPrice, x.PlannedAmt, x.PlannedMarginAmt, x.CommittedAmt, x.M_Product_ID,
    x.M_Product_Category_ID, x.InvoicedAmt, x.InvoicedQty, x.CommittedQty, x.C_ProjectIssue_ID, x.C_Order_ID,
    x.C_OrderPO_ID, x.IsPrinted, x.Processed, x.C_ProjectPhase_ID, x.C_ProjectTask_ID, x.S_ResourceAssignment_ID,
    x.Vendor_ID, x.PP_Product_BOM_ID, x.AD_Workflow_ID, x.PP_Order_ID, x.C_RfQLine_ID, x.C_UOM_ID, x.DatePromised,
    x.EndDate, x.M_ProductionBatch_ID, x.QtyEntered, x.DurationUnit, x.DurationEstimated, x.C_ProjectLineType_ID,
    x.C_ProjectStatus_ID, x.C_ProjectTaskCategory_ID, x.C_StandardProjectLine_ID, x.DateDeadline,
    x.DateFinishSchedule, x.DateLastRun, x.DateNextRun, x.DateStartSchedule, x.DurationReal, x.Frequency,
    x.FrequencyType, x.Help, x.IsComplete, x.IsIndefinite, x.IsMilestone, x.IsRecurrent, x.IsSummary, x.Name,
    x.Parent_ID, x.PercentageCompleted, x.PriorityRule, x.ProjInvoiceRule, x.Responsible_ID, x.RunsMax,
    x.RunsRemaining, x.StartDate, x.ProjectLineType, x.IsDropShip, x.DropShip_BPartner_ID, x.DropShip_Location_ID,
    x.PriceEntered, x.SP027_Brand_ID, x.SP027_Period_ID, x.SP027_PBudgetLine_ID, x.SP027_BrandProduct_ID,
    x.SP027_PlannedAmt, x.IsCostBased, x.Margin, x.Cost, x.S_ResourceType_ID, x.Ref_BPartner_ID,
    x.IsCustomerApproved, x.CostPlannedAmt, x.CostOrderedAmt, x.CostInvoicedAmt, x.CostReceivedAmt,
    x.CostConsumedAmt, x.QtyOrdered, x.QtyDelivered, x.CostOrderedQty, x.CostReceivedQty, x.CostConsumedQty,
    x.CostInvoicedQty, x.OrderedAmt, x.DeliveredAmt, x.ProfitPlannedAmt, x.ProfitRealizedAmt,
    x.SP027_AdvertisingRule_ID, x.SP027_ResourceQuantity,
    x.ProjectValue,
    x.ProjectName,
    x.ProjectStatus_ID,
    CAST(x.ProjectIsOpen AS INTEGER),
    x.ProjectManager_ID,
    x.C_BPartner_ID,
    x.C_ProjectType_ID,
    x.ProjectDeadline,
    CAST(x.Kind AS CHAR(1)),
    CAST(CASE WHEN x.Kind = 'F' THEN 1 ELSE 0 END AS INTEGER),
    CAST(CASE WHEN x.Kind = 'H' THEN 1 ELSE 0 END AS INTEGER),
    CAST(CASE WHEN x.Kind = 'R' THEN 1 ELSE 0 END AS INTEGER),
    CAST(CASE WHEN x.Kind IN ('R', 'L') THEN 1 ELSE 0 END AS INTEGER),
    CAST(1 AS INTEGER),
    CAST((CASE WHEN x.IsComplete = 'Y' OR COALESCE(x.PercentageCompleted, 0) >= 100 THEN 1 ELSE 0 END) AS INTEGER),
    CAST((CASE WHEN (CASE WHEN x.IsComplete = 'Y' OR COALESCE(x.PercentageCompleted, 0) >= 100 THEN 1 ELSE 0 END) = 0 AND x.IsActive = 'Y' AND x.DateDeadline IS NOT NULL AND CAST(x.DateDeadline AS DATE) < CURRENT_DATE THEN 1 ELSE 0 END) AS INTEGER),
    CASE WHEN (CASE WHEN (CASE WHEN x.IsComplete = 'Y' OR COALESCE(x.PercentageCompleted, 0) >= 100 THEN 1 ELSE 0 END) = 0 AND x.IsActive = 'Y' AND x.DateDeadline IS NOT NULL AND CAST(x.DateDeadline AS DATE) < CURRENT_DATE THEN 1 ELSE 0 END) = 1 THEN CURRENT_DATE - CAST(x.DateDeadline AS DATE) ELSE 0 END,
    CASE WHEN x.DateDeadline IS NULL THEN NULL ELSE CAST(x.DateDeadline AS DATE) - CURRENT_DATE END,
    CASE WHEN x.Responsible_ID IS NOT NULL THEN 1 ELSE 0 END,
    CASE WHEN x.DateDeadline IS NOT NULL THEN 1 ELSE 0 END,
    CASE WHEN x.DurationReal IS NOT NULL AND x.DurationEstimated IS NOT NULL THEN x.DurationReal - x.DurationEstimated ELSE NULL END,
    COALESCE(x.PlannedAmt, 0) - COALESCE(x.InvoicedAmt, 0),
    CASE WHEN COALESCE(x.PlannedAmt, 0) <> 0 THEN ROUND(COALESCE(x.CommittedAmt, 0) * 100 / x.PlannedAmt, 2) ELSE NULL END,
    CASE WHEN COALESCE(x.PlannedAmt, 0) <> 0 THEN ROUND(COALESCE(x.InvoicedAmt, 0) * 100 / x.PlannedAmt, 2) ELSE NULL END,
    CASE WHEN COALESCE(x.PlannedAmt, 0) <> 0 THEN ROUND(COALESCE(x.PlannedMarginAmt, 0) * 100 / x.PlannedAmt, 2) ELSE NULL END,
    CAST(x.ParentKind AS CHAR(1)),
    x.ParentName
FROM (
    SELECT l.C_ProjectLine_ID,
        l.AD_Client_ID, l.AD_Org_ID, l.IsActive, l.Created, l.Updated, l.C_Project_ID, l.Line, l.Description,
        l.PlannedQty, l.PlannedPrice, l.PlannedAmt, l.PlannedMarginAmt, l.CommittedAmt, l.M_Product_ID,
        l.M_Product_Category_ID, l.InvoicedAmt, l.InvoicedQty, l.CommittedQty, l.C_ProjectIssue_ID, l.C_Order_ID,
        l.C_OrderPO_ID, l.IsPrinted, l.Processed, l.C_ProjectPhase_ID, l.C_ProjectTask_ID, l.S_ResourceAssignment_ID,
        l.Vendor_ID, l.PP_Product_BOM_ID, l.AD_Workflow_ID, l.PP_Order_ID, l.C_RfQLine_ID, l.C_UOM_ID,
        l.DatePromised, l.EndDate, l.M_ProductionBatch_ID, l.QtyEntered, l.DurationUnit, l.DurationEstimated,
        l.C_ProjectLineType_ID, l.C_ProjectStatus_ID, l.C_ProjectTaskCategory_ID, l.C_StandardProjectLine_ID,
        l.DateDeadline, l.DateFinishSchedule, l.DateLastRun, l.DateNextRun, l.DateStartSchedule, l.DurationReal,
        l.Frequency, l.FrequencyType, l.Help, l.IsComplete, l.IsIndefinite, l.IsMilestone, l.IsRecurrent,
        l.IsSummary, l.Name, l.Parent_ID, l.PercentageCompleted, l.PriorityRule, l.ProjInvoiceRule, l.Responsible_ID,
        l.RunsMax, l.RunsRemaining, l.StartDate, l.ProjectLineType, l.IsDropShip, l.DropShip_BPartner_ID,
        l.DropShip_Location_ID, l.PriceEntered, l.SP027_Brand_ID, l.SP027_Period_ID, l.SP027_PBudgetLine_ID,
        l.SP027_BrandProduct_ID, l.SP027_PlannedAmt, l.IsCostBased, l.Margin, l.Cost, l.S_ResourceType_ID,
        l.Ref_BPartner_ID, l.IsCustomerApproved, l.CostPlannedAmt, l.CostOrderedAmt, l.CostInvoicedAmt,
        l.CostReceivedAmt, l.CostConsumedAmt, l.QtyOrdered, l.QtyDelivered, l.CostOrderedQty, l.CostReceivedQty,
        l.CostConsumedQty, l.CostInvoicedQty, l.OrderedAmt, l.DeliveredAmt, l.ProfitPlannedAmt, l.ProfitRealizedAmt,
        l.SP027_AdvertisingRule_ID, l.SP027_ResourceQuantity, p.Value AS ProjectValue, p.Name AS ProjectName,
        p.C_ProjectStatus_ID AS ProjectStatus_ID,
        CASE WHEN p.C_Project_ID IS NOT NULL AND p.IsActive = 'Y' AND COALESCE(ps.IsClosed, 'N') = 'N' THEN 1 ELSE 0 END AS ProjectIsOpen,
        p.ProjectManager_ID, p.C_BPartner_ID, p.C_ProjectType_ID, p.DateDeadline AS ProjectDeadline,
        par.Name AS ParentName,
        CASE WHEN l.ProjectLineType = 'P' OR l.IsSummary = 'Y' THEN 'F' WHEN l.ProjectLineType = 'M' OR l.IsMilestone = 'Y' THEN 'H' WHEN l.ProjectLineType = 'R' THEN 'R' ELSE 'L' END AS Kind,
        CASE WHEN par.C_ProjectLine_ID IS NULL THEN NULL WHEN par.ProjectLineType = 'P' OR par.IsSummary = 'Y' THEN 'F' WHEN par.ProjectLineType = 'M' OR par.IsMilestone = 'Y' THEN 'H' WHEN par.ProjectLineType = 'R' THEN 'R' ELSE 'L' END AS ParentKind
    FROM C_ProjectLine l
        LEFT JOIN C_Project p ON (p.C_Project_ID = l.C_Project_ID)
        LEFT JOIN C_ProjectStatus ps ON (ps.C_ProjectStatus_ID = p.C_ProjectStatus_ID)
        LEFT JOIN C_ProjectLine par ON (par.C_ProjectLine_ID = l.Parent_ID)
) x;
